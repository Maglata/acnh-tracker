#!/usr/bin/env node
// Downloads the New Horizons critter lists from the Animal Crossing Wiki and
// regenerates public/data/critters.js.
import { mkdir, stat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATEGORIES, parseCategory } from './lib/wiki.mjs';

const API = 'https://animalcrossing.fandom.com/api.php';
const WIKI = 'https://animalcrossing.fandom.com/wiki/';
const OUT = fileURLToPath(new URL('../public/data/critters.js', import.meta.url));
const IMG_DIR = fileURLToPath(new URL('../public/img/', import.meta.url));
const HEADERS = { 'User-Agent': 'acnh-tracker (local personal tracker)', Referer: 'https://animalcrossing.fandom.com/' };
const FORCE = process.argv.includes('--force');

async function api(params) {
  const url = `${API}?${new URLSearchParams({ format: 'json', formatversion: '2', ...params })}`;
  const res = await fetch(url, { headers: HEADERS });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return res.json();
}

// The wiki CDN rejects requests without a fandom Referer, so icons are stored locally.
async function downloadImage(file, url) {
  const target = join(IMG_DIR, file);
  if (!FORCE && (await stat(target).catch(() => null))) return false;
  const res = await fetch(`${url}${url.includes('?') ? '&' : '?'}format=original`, { headers: HEADERS });
  if (!res.ok) throw new Error(`${res.status} downloading ${url}`);
  await writeFile(target, Buffer.from(await res.arrayBuffer()));
  return true;
}

async function fetchWikitext(page) {
  const data = await api({ action: 'parse', page, prop: 'wikitext' });
  if (data.error) throw new Error(`${page}: ${data.error.info}`);
  return data.parse.wikitext;
}

async function resolveImages(files) {
  const urls = new Map();
  for (let i = 0; i < files.length; i += 50) {
    const batch = files.slice(i, i + 50);
    const data = await api({
      action: 'query',
      prop: 'imageinfo',
      iiprop: 'url',
      iiurlwidth: '64',
      titles: batch.map((f) => `File:${f}`).join('|'),
    });
    const normalized = new Map((data.query.normalized ?? []).map((n) => [n.to, n.from]));
    for (const page of data.query.pages) {
      const info = page.imageinfo?.[0];
      if (!info) continue;
      const original = (normalized.get(page.title) ?? page.title).replace(/^File:/, '');
      urls.set(original, info.thumburl ?? info.url);
    }
  }
  return urls;
}

const critters = [];
for (const [category, { page, label }] of Object.entries(CATEGORIES)) {
  const list = parseCategory(category, await fetchWikitext(page));
  console.log(`${label}: ${list.length}`);
  critters.push(...list);
}

const ids = new Set();
for (const c of critters) {
  if (ids.has(c.id)) throw new Error(`Duplicate id ${c.id}`);
  ids.add(c.id);
}

const images = await resolveImages([...new Set(critters.map((c) => c.imageFile).filter(Boolean))]);
await mkdir(IMG_DIR, { recursive: true });
let downloaded = 0;
for (const c of critters) {
  const url = images.get(c.imageFile);
  c.wiki = WIKI + encodeURIComponent(c.page.replace(/ /g, '_'));
  c.image = null;
  if (!url) {
    console.warn(`No image for ${c.name}`);
    continue;
  }
  try {
    if (await downloadImage(c.imageFile, url)) downloaded++;
    c.image = `img/${c.imageFile}`;
  } catch (err) {
    console.warn(`${c.name}: ${err.message}`);
  }
}
console.log(`Downloaded ${downloaded} new icons to ${IMG_DIR}`);

const body = critters.map((c) => '    ' + JSON.stringify(c)).join(',\n');
await writeFile(
  OUT,
  `// Generated by scripts/update-data.mjs from the Animal Crossing Wiki (${WIKI}). Do not edit by hand.
window.ACNH_DATA = {
  "source": ${JSON.stringify(WIKI)},
  "updatedAt": ${JSON.stringify(new Date().toISOString())},
  "critters": [
${body}
  ]
};
`,
);
console.log(`Wrote ${critters.length} critters to ${OUT}`);
